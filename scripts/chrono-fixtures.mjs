// Regenerates Tests/RemiCoreTests/ChronoFixtures.swift from chrono-node, the date parser remi uses.
//
// Usage (from a checkout of https://github.com/mattheworiordan/remi with `npm ci` done):
//   TZ=UTC node /path/to/reminders/scripts/chrono-fixtures.mjs phrases.json > ChronoFixtures.swift
// where phrases.json is a JSON array of phrases. Each phrase is evaluated exactly like remi's
// parseDate(): YYYY-MM-DD passes through, otherwise chrono.parse(text, ref, { forwardDate: true })[0].
import fs from "node:fs";
import { createRequire } from "node:module";
const require = createRequire(`${process.cwd()}/package.json`);
const chrono = require("chrono-node");
const chronoVersion = JSON.parse(fs.readFileSync(`${process.cwd()}/node_modules/chrono-node/package.json`, "utf8")).version;

const refs = [
  "2026-10-23T10:00:00Z", // Friday morning
  "2026-10-19T10:00:00Z", // Monday morning
  "2026-12-30T10:00:00Z", // Wednesday, year end
  "2026-10-25T23:30:00Z", // Sunday, late night
  "2026-10-24T08:15:00Z", // Saturday morning
  "2028-01-31T18:00:00Z", // Monday evening, month end in a leap year
];
const phrases = JSON.parse(fs.readFileSync(process.argv[2], "utf8"));
const iso = /^\d{4}-\d{2}-\d{2}$/;
const lines = [];
for (const ref of refs) {
  for (const phrase of phrases) {
    const trimmed = phrase.trim();
    let expected = null;
    if (iso.test(trimmed)) {
      expected = trimmed;
    } else {
      const results = chrono.parse(trimmed, new Date(ref), { forwardDate: true });
      if (results.length > 0) {
        const d = results[0].start.date();
        expected = `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, "0")}-${String(d.getDate()).padStart(2, "0")}`;
      }
    }
    lines.push(`  ChronoCase(${JSON.stringify(ref)}, ${JSON.stringify(phrase)}, ${expected === null ? "nil" : JSON.stringify(expected)}),`);
  }
}
process.stdout.write(`// Generated by scripts/chrono-fixtures.mjs from chrono-node ${chronoVersion} with TZ=UTC.
// Do not edit by hand. Each case: reference instant, input, expected YYYY-MM-DD (nil = remi throws).

let chronoCases: [ChronoCase] = [
${lines.join("\n")}
]
`);
