// Regenerates Tests/RemindersCoreTests/DateReferenceCases.swift: the reference results DueDateParser is tested
// against, produced by chrono-node (a mature natural-language date parser for JavaScript).
//
// Usage, from any directory where `npm install chrono-node@2.9` has been run:
//   TZ=UTC node /path/to/reminders/scripts/date-reference-cases.mjs /path/to/reminders/scripts/date-phrases.json \
//     > /path/to/reminders/Tests/RemindersCoreTests/DateReferenceCases.swift
// Each phrase is evaluated the way DueDateParser is specified: a valid YYYY-MM-DD passes through (an invalid one is
// rejected), otherwise the first result of chrono.parse(text, ref, { forwardDate: true }).
import fs from "node:fs";
import { createRequire } from "node:module";
const require = createRequire(`${process.cwd()}/package.json`);
const chrono = require("chrono-node");
const chronoVersion = JSON.parse(fs.readFileSync(`${process.cwd()}/node_modules/chrono-node/package.json`, "utf8")).version;

const refs = [
  "2026-10-23T10:00:00Z", // Friday morning
  "2026-10-19T10:00:00Z", // Monday morning
  "2026-12-30T10:00:00Z", // Wednesday, year end
  "2026-10-25T23:30:00Z", // Sunday, late night
  "2026-10-24T08:15:00Z", // Saturday morning
  "2028-01-31T18:00:00Z", // Monday evening, month end in a leap year
];
const phrases = JSON.parse(fs.readFileSync(process.argv[2], "utf8"));
const iso = /^\d{4}-\d{2}-\d{2}$/;
const lines = [];
for (const ref of refs) {
  for (const phrase of phrases) {
    const trimmed = phrase.trim();
    let expected = null;
    if (iso.test(trimmed)) {
      const [y, m, d] = trimmed.split("-").map(Number);
      const date = new Date(Date.UTC(y, m - 1, d));
      const valid = date.getUTCFullYear() === y && date.getUTCMonth() === m - 1 && date.getUTCDate() === d;
      expected = valid ? trimmed : null;
    } else {
      const results = chrono.parse(trimmed, new Date(ref), { forwardDate: true });
      if (results.length > 0) {
        const d = results[0].start.date();
        expected = `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, "0")}-${String(d.getDate()).padStart(2, "0")}`;
      }
    }
    lines.push(`  DateReferenceCase(${JSON.stringify(ref)}, ${JSON.stringify(phrase)}, ${expected === null ? "nil" : JSON.stringify(expected)}),`);
  }
}
process.stdout.write(`// Generated by scripts/date-reference-cases.mjs from chrono-node ${chronoVersion} with TZ=UTC: what a mature natural-language
// date parser makes of each phrase (with forward dates), used as the reference for DueDateParser.
// Do not edit by hand. Each case: reference instant, input, expected YYYY-MM-DD (nil = rejected).

let dateReferenceCases: [DateReferenceCase] = [
${lines.join("\n")}
]
`);
